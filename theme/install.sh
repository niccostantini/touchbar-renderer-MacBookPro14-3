#!/bin/sh
# Installs the Leo Camp desktop theme for the current user (no sudo).
# Needs: gnome-shell-extensions (User Themes) and papirus-icon-theme from apt,
# and the Fraunces font in ~/.local/share/fonts.
# Saves the previous settings to ~/.config/leocamp/restore.sh first.
# Uso: sh theme/install.sh        Ripristino: sh ~/.config/leocamp/restore.sh
set -eu

THEME=$(cd "$(dirname "$0")" && pwd)
DATA=${XDG_DATA_HOME:-$HOME/.local/share}
CONFIG=${XDG_CONFIG_HOME:-$HOME/.config}
DOCK=org.gnome.shell.extensions.dash-to-dock
USER_THEME=user-theme@gnome-shell-extensions.gcampax.github.com

python3 -I "$THEME/build.py"

# 1. Restore script with the current values (only on the first install).
mkdir -p "$CONFIG/leocamp"
RESTORE="$CONFIG/leocamp/restore.sh"
if [ ! -e "$RESTORE" ]; then
	{
		echo "#!/bin/sh"
		echo "# Generated by theme/install.sh: puts the desktop back as it was."
		echo "systemctl --user disable --now leocamp-scheme.service 2>/dev/null"
		for kv in \
			"org.gnome.desktop.interface icon-theme" \
			"org.gnome.desktop.interface accent-color" \
			"org.gnome.desktop.background picture-uri" \
			"org.gnome.desktop.background picture-uri-dark" \
			"org.gnome.shell enabled-extensions" \
			"$DOCK dock-position" "$DOCK extend-height" "$DOCK dash-max-icon-size" \
			"$DOCK custom-theme-customize-running-dots" "$DOCK custom-theme-running-dots-color"; do
			# shellcheck disable=SC2086
			echo "gsettings set $kv \"$(gsettings get $kv)\""
		done
		echo "gsettings reset org.gnome.shell.extensions.user-theme name 2>/dev/null"
		for f in gtk-4.0/gtk.css gtk-3.0/gtk.css; do
			if [ -e "$CONFIG/$f" ] && [ ! -L "$CONFIG/$f" ]; then
				cp "$CONFIG/$f" "$CONFIG/leocamp/$(echo "$f" | tr / _).orig"
				echo "cp '$CONFIG/leocamp/$(echo "$f" | tr / _).orig' '$CONFIG/$f'"
			else
				echo "rm -f '$CONFIG/$f'"
			fi
		done
		echo "rm -rf '$HOME/.themes/LeoCamp' '$HOME/.themes/LeoCamp-Dark' '$DATA/icons/LeoCamp-Papirus' '$DATA/icons/LeoCamp-Papirus-Dark'"
		echo "echo 'Ripristinato. Fai logout e login per la Shell.'"
	} >"$RESTORE"
	chmod +x "$RESTORE"
fi

# 2. Files: symlinks into the repository, so `git pull` + build updates them.
mkdir -p "$HOME/.themes" "$DATA/icons" "$DATA/backgrounds" "$CONFIG/gtk-4.0" "$CONFIG/gtk-3.0"
for name in LeoCamp LeoCamp-Dark; do
	ln -sfn "$THEME/dist/themes/$name" "$HOME/.themes/$name"
done
for name in LeoCamp-Papirus LeoCamp-Papirus-Dark; do
	ln -sfn "$THEME/dist/icons/$name" "$DATA/icons/$name"
done
ln -sf "$THEME/dist/gtk-4.0/gtk.css" "$CONFIG/gtk-4.0/gtk.css"
ln -sf "$THEME/dist/gtk-3.0/gtk.css" "$CONFIG/gtk-3.0/gtk.css"
cp "$THEME/dist/backgrounds/"leocamp-*.svg "$DATA/backgrounds/"

# 3. Settings.
gsettings set org.gnome.desktop.background picture-uri "file://$DATA/backgrounds/leocamp-light.svg"
gsettings set org.gnome.desktop.background picture-uri-dark "file://$DATA/backgrounds/leocamp-dark.svg"
gsettings set org.gnome.desktop.background picture-options zoom
gsettings set org.gnome.desktop.interface accent-color purple
gsettings set $DOCK dock-position BOTTOM
gsettings set $DOCK extend-height false
gsettings set $DOCK dash-max-icon-size 44
gsettings set $DOCK custom-theme-customize-running-dots true
gsettings set $DOCK custom-theme-running-dots-color '#f2369b'
case "$(gsettings get org.gnome.shell enabled-extensions)" in
*"$USER_THEME"*) ;;
*) # Takes effect at the next login on Wayland.
	gsettings set org.gnome.shell enabled-extensions \
		"$(gsettings get org.gnome.shell enabled-extensions | sed "s/@as //; s/^\[\]$/['$USER_THEME']/; t; s/\]$/, '$USER_THEME']/")" ;;
esac

# 4. Light/dark follower.
mkdir -p "$CONFIG/systemd/user"
cat >"$CONFIG/systemd/user/leocamp-scheme.service" <<EOF
[Unit]
Description=Leo Camp: follow GNOME light/dark style
PartOf=graphical-session.target
After=graphical-session.target

[Service]
ExecStart=/bin/sh $THEME/leocamp-follow-scheme
Restart=on-failure

[Install]
WantedBy=graphical-session.target
EOF
systemctl --user daemon-reload
systemctl --user enable --now leocamp-scheme.service
systemctl --user restart leocamp-scheme.service

echo "Leo Camp installato. Fai logout e login per attivare il tema della Shell."
echo "Ripristino: sh $RESTORE"
